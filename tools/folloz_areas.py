"""The outlines of the countries where Folloz offers national map layers (docs/track/folloz.md « The map »).

Reads Natural Earth's 1:10m countries (public domain, the copy tools/countrymaps.py fetched into $CN_DATA_DIR/naturalearth),
keeps each area's polygons — France's metropolitan ones, Switzerland's and Liechtenstein's —, simplifies them (Douglas-Peucker,
about 1 km) and writes functions/_lib/follozareas.js. Run again only to add an area:

    py tools/folloz_areas.py
"""
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(os.environ.get("CN_DATA_DIR") or ROOT.parent / "data")
SRC = DATA / "naturalearth" / "ne_10m_admin_0_countries.geojson"
OUT = ROOT / "functions" / "_lib" / "follozareas.js"

# area id -> (Natural Earth ISO_A3 codes, a box the polygons kept must lie in: lon0, lat0, lon1, lat1)
AREAS = {
    "FR": (["FRA"], (-6.0, 41.0, 10.0, 51.6)),
    "CH": (["CHE", "LIE"], (5.5, 45.5, 10.8, 48.0)),
}
TOL = 0.008  # degrees: ~0.9 km of latitude, ~0.6 km of longitude here


def dp(points, tol):
    """Douglas-Peucker on a closed ring (first point = last)."""
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        ll = dx * dx + dy * dy
        far, at = -1.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            if ll == 0:
                d = (px - ax) ** 2 + (py - ay) ** 2
            else:
                t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / ll))
                d = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2
            if d > far:
                far, at = d, i
        if at >= 0 and far > tol * tol:
            keep[at] = True
            stack.append((a, at))
            stack.append((at, b))
    return [p for p, k in zip(points, keep) if k]


def code_of(props):
    for k in ("ISO_A3", "ADM0_A3", "SOV_A3"):
        v = props.get(k)
        if v and v != "-99":
            return v
    return None


def main():
    feats = json.loads(SRC.read_text(encoding="utf-8"))["features"]
    out = {}
    for area, (codes, box) in AREAS.items():
        polys = []
        for f in feats:
            if code_of(f["properties"]) not in codes and f["properties"].get("ADM0_A3") not in codes:
                continue
            g = f["geometry"]
            parts = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
            for poly in parts:
                ring = poly[0]  # the outer ring; no country here has a hole that matters at this scale
                lons = [p[0] for p in ring]
                lats = [p[1] for p in ring]
                if min(lons) < box[0] or max(lons) > box[2] or min(lats) < box[1] or max(lats) > box[3]:
                    continue
                simple = dp([(round(p[0], 4), round(p[1], 4)) for p in ring], TOL)
                if len(simple) >= 4:
                    polys.append([[x, y] for x, y in simple])
        out[area] = polys
        print(area, len(polys), "polygons,", sum(len(p) for p in polys), "points")
    body = json.dumps(out, separators=(",", ":"))
    OUT.write_text(
        "// Generated by tools/folloz_areas.py from Natural Earth's 1:10m countries (public domain): the outlines of the areas\n"
        "// where Folloz offers national map layers, [lon, lat], simplified to about 1 km. Do not edit by hand.\n"
        f"export const AREAS = {body};\n",
        encoding="utf-8", newline="\n")
    print("written", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
